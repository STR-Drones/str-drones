<script lang="ts" setup>
import gsap from 'gsap'
import { onMounted } from 'vue'
import ScrollTrigger from 'gsap/ScrollTrigger'
let tl = null

const mouseEnter = () => {
  let helpertl =  gsap.timeline({ ease: 'none', paused: true})
  helpertl.add(tl.tweenFromTo(tl.progress(), 'loop', { ease: 'none'}))
  helpertl.add(tl.tweenFromTo('loop', tl.duration(), { repeat: -1, ease: 'none'}))
  helpertl.play()
}

const mouseExit = () => {
  tl.tweenFromTo(tl.progress(), 0, { ease: 'none'})
}

onMounted(() => {
  gsap.utils.toArray('.aspes-nav').forEach((group) => {
    const box = group.getBBox()
    const cx = box.x + box.width / 2
    const cy = box.y + box.height / 2

    gsap.set(group, {
      svgOrigin: `${cx} ${cy}`,
      transformOrigin: 'center center'
    })
  })

  gsap.set('.str-logo-animated', {
    opacity: 1,
  })

  tl = gsap.timeline({ ease: 'none', paused: true})

  tl.fromTo('.aspes-nav-rect', {
    rotation: -45
  }, {
    rotation: 0,
    duration: .2,
  })
  tl.addLabel('loop')
  tl.to('.aspes-nav', {
    rotation: 360,
    duration: 2,
    ease: 'none'
  })
})
</script>

